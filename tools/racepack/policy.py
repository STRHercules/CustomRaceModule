"""Strict, deterministic server admission definitions. No allocation or codec migration."""

import hashlib
import json
import re
from pathlib import Path


STOCK_RACES = frozenset({1, 2, 3, 4, 5, 6, 7, 8, 10, 11})


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def load_policy(path: Path) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=_unique_object)
    validate_policy(data)
    return data


def validate_policy(data: dict) -> None:
    if not isinstance(data, dict) or set(data) != {"schema_version", "identities", "unresolved"}:
        raise ValueError("policy requires exactly schema_version, identities, unresolved")
    if type(data["schema_version"]) is not int or data["schema_version"] != 1:
        raise ValueError("unsupported policy schema version")
    if not isinstance(data["identities"], list) or not isinstance(data["unresolved"], list):
        raise ValueError("identities and unresolved must be arrays")
    if any(not isinstance(item, str) or not item.strip() for item in data["unresolved"]):
        raise ValueError("unresolved entries must be nonempty strings")
    keys, races = set(), set()
    for row in data["identities"]:
        if not isinstance(row, dict) or set(row) != {"key", "race_id", "legacy_mask_donor"}:
            raise ValueError("identity requires exactly key, race_id, legacy_mask_donor")
        key, race, donor = row["key"], row["race_id"], row["legacy_mask_donor"]
        if not isinstance(key, str) or not re.fullmatch(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*", key):
            raise ValueError("identity key must be a stable lowercase slug")
        if type(race) is not int or not 1 <= race <= 128 or race in STOCK_RACES:
            raise ValueError("custom race ID must be within 1..128 and cannot claim a stock race")
        if type(donor) is not int or donor not in STOCK_RACES:
            raise ValueError("legacy mask donor must be an original playable Wrath race")
        if key in keys or race in races:
            raise ValueError("duplicate identity key or race ID")
        keys.add(key)
        races.add(race)


def canonical_policy(data: dict) -> bytes:
    validate_policy(data)
    normalized = dict(data, identities=sorted(data["identities"], key=lambda row: row["key"]),
                      unresolved=sorted(data["unresolved"]))
    return (json.dumps(normalized, sort_keys=True, ensure_ascii=True, separators=(",", ":")) + "\n").encode()


def generate_header(data: dict) -> bytes:
    digest = hashlib.sha256(canonical_policy(data)).hexdigest()
    rows = sorted(data["identities"], key=lambda row: row["race_id"])
    lines = ["// Generated by tools.racepack.policy; do not edit.", "#ifndef CUSTOM_RACES_DEFINITIONS_H",
             "#define CUSTOM_RACES_DEFINITIONS_H", '#include "RacePolicy.h"', "namespace CustomRaces",
             "{", f'inline constexpr char PolicyDigest[] = "{digest}";',
             f"inline constexpr bool IdentityPolicyResolved = {'false' if data['unresolved'] else 'true'};",
             "inline constexpr RaceSet InstalledRaces = []", "{", "    RaceSet races{};"]
    lines.extend(f"    races[{row['race_id']}] = true; // {row['key']}" for row in rows)
    lines.extend(["    return races;", "}();", "}", "#endif", ""])
    return "\n".join(lines).encode()
